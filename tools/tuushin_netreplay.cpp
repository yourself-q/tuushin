int main(int argc, char** argv) {
  std::signal(SIGINT, on_signal);
  std::signal(SIGTERM, on_signal);
  std::signal(SIGHUP, on_signal);
  if (argc < 2) {
    usage();
    return 1;
  }
  const std::string mode = argv[1];
  try {
    int i = 2;
    auto next = [&]() -> std::string {
      if (i + 1 >= argc) throw std::runtime_error(std::string("missing value for ") + argv[i]);
      return argv[++i];
    };
    auto port = [&](const std::string& s) {
      const double p = parse_double(s, "port");
      if (p < 1 || p > 65535) throw std::runtime_error("bad port: " + s);
      return static_cast<std::uint16_t>(p);
    };
    auto micros = [&](const std::string& s) {
      const double v = parse_double(s, "bin");
      if (!(v > 0)) throw std::runtime_error("bad bin: " + s);
      return static_cast<Nanos>(std::llround(v * 1e3));
    };
    if (mode == "run") {
      RunOptions o;
      for (; i < argc; ++i) {
        const std::string a = argv[i];
        if (a == "--dev") o.dev = next();
        else if (a == "--trace") o.trace = next();
        else if (a == "--port") o.port = port(next());
        else if (a == "--start") o.start = parse_nanos(next(), "start");
        else if (a == "--bin") o.bin = micros(next());
        else if (a == "--flow-limit") o.flow_limit = static_cast<unsigned>(parse_nanos(next(), "flow-limit"));
        else throw std::runtime_error("unknown option " + a);
      }
      return run_replay(o);
    }
    if (mode == "stop") {
      std::string dev;
      for (; i < argc; ++i) {
        const std::string a = argv[i];
        if (a == "--dev") dev = next();
        else throw std::runtime_error("unknown option " + a);
      }
      return run_stop(dev);
    }
    if (mode == "clock") {
      std::printf("%lld\n", static_cast<long long>(monotonic_now()));
      return 0;
    }
    if (mode == "send") {
      SendOptions o;
      for (; i < argc; ++i) {
        const std::string a = argv[i];
        if (a == "--port") o.port = port(next());
        else if (a == "--rate") o.rate = parse_double(next(), "rate");
        else if (a == "--duration") o.duration = parse_double(next(), "duration");
        else if (a == "--size") o.size = static_cast<std::size_t>(parse_double(next(), "size"));
        else if (!a.empty() && a[0] != '-' && o.host.empty()) o.host = a;
        else throw std::runtime_error("unknown option " + a);
      }
      return run_send(o);
    }
    if (mode == "recv") {
      RecvOptions o;
      for (; i < argc; ++i) {
        const std::string a = argv[i];
        if (a == "--port") o.port = port(next());
        else if (a == "--out") o.out = next();
        else if (a == "--start") o.start = parse_nanos(next(), "start");
        else if (a == "--idle") o.idle = parse_double(next(), "idle");
        else throw std::runtime_error("unknown option " + a);
      }
      return run_recv(o);
    }
    if (mode == "compare") {
      std::string trace, recorded;
      Nanos bin = 0;
      for (; i < argc; ++i) {
        const std::string a = argv[i];
        if (a == "--trace") trace = next();
        else if (a == "--recorded") recorded = next();
        else if (a == "--bin") bin = micros(next());
        else throw std::runtime_error("unknown option " + a);
      }
      return run_compare(trace, recorded, bin);
    }
    usage();
    return 1;
  } catch (const std::exception& e) {
    std::fprintf(stderr, "tuushin-netreplay: %s\n", e.what());
    return 1;
  }
}
