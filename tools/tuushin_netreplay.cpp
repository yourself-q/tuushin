// tuushin-netreplay: replays a recorded one-way path, a trace from
// tuushin-probe, on a Linux interface, datagram by datagram, for emulators
// that run real network stacks: network namespaces, Mininet and the
// testbeds built on it.
//
//   tuushin-netreplay run --dev s1-eth2 --trace home-vps.fwd.csv --port 47000
//
// Every UDP datagram the interface sends (from or to --port) is held for the
// delay the trace recorded at the moment it is sent, or dropped where the
// trace lost its packet (netreplay/netreplay.bpf.c); the trace loops. Ctrl-C
// detaches the program and returns the interface's root qdisc to the
// system's default.
//
// Attach on a hop that forwards the traffic (a router namespace, a switch
// port), not on the host that sends it: a datagram held in the sender's own
// qdisc still counts against its socket's send buffer, and a fast flow held
// long enough fills it, after which the sends are refused (see
// netreplay_lab.sh --at-sender).
//
// The root qdisc becomes fq, which is what honours the departure times the
// program sets. Whatever else was there is replaced: give a replayed link
// no tc parameters of its own (in Mininet, no bw or delay on its TCLink).
//
// Needs root (CAP_BPF and CAP_NET_ADMIN), Linux 5.0 or later and tc from
// iproute2. For checking a replay on one host, whose network namespaces
// share CLOCK_MONOTONIC, it also sends and receives stamped datagrams and
// compares what they met with the trace; tools/netreplay_lab.sh does that.

