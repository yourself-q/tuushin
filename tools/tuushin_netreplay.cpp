volatile std::sig_atomic_t g_stop = 0;

void on_signal(int) { g_stop = 1; }

// The filter's place among the interface's egress filters, fixed so that
// `stop` finds the one a killed run left.
constexpr __u32 kHandle = 0x7475;  // "tu"
constexpr __u32 kPriority = 1;

// The datagrams of `send` and `recv`.
constexpr std::uint32_t kMagic = 0x544e5250;  // "TNRP"
constexpr std::size_t kStampSize = 16;        // magic, sequence number, send time

void usage() {
  std::fprintf(stderr,
               "usage:\n"
               "  tuushin-netreplay run --dev IF --trace FILE [options]\n"
               "      --port P          replay only UDP from or to port P (all UDP)\n"
               "      --start NS        CLOCK_MONOTONIC time of the trace's offset 0 (now)\n"
               "      --bin US          spacing of the replayed points (the trace's\n"
               "                        median send interval)\n"
               "      --flow-limit N    fq's datagrams per flow (enough for 20 kHz\n"
               "                        over the trace's longest delay, at least 1000)\n"
               "  tuushin-netreplay stop --dev IF\n"
               "      removes what a killed run left on IF\n"
               "  tuushin-netreplay clock\n"
               "      prints CLOCK_MONOTONIC in ns, for --start\n"
               "  tuushin-netreplay send HOST --port P [--rate HZ] [--duration S] [--size B]\n"
               "      stamped datagrams (1000 Hz, 10 s, 100 bytes)\n"
               "  tuushin-netreplay recv --port P --out FILE [--start NS] [--idle S]\n"
               "      writes the path the stamped datagrams met as a trace, send\n"
               "      times from --start (the first send); ends when nothing has\n"
               "      come for S seconds (5) or on Ctrl-C\n"
               "  tuushin-netreplay compare --trace FILE --recorded FILE [--bin US]\n"
               "      compares a recorded path with the trace replayed on it\n");
}

double parse_double(const std::string& s, const char* what) {
  char* end = nullptr;
  const double v = std::strtod(s.c_str(), &end);
  if (end == s.c_str() || *end != '\0') throw std::runtime_error(std::string("bad ") + what + ": " + s);
  return v;
}

Nanos parse_nanos(const std::string& s, const char* what) {
  char* end = nullptr;
  const long long v = std::strtoll(s.c_str(), &end, 10);
  if (end == s.c_str() || *end != '\0' || v < 0) {
    throw std::runtime_error(std::string("bad ") + what + ": " + s);
  }
  return static_cast<Nanos>(v);
}

// Runs tc from iproute2; true if it exited 0. With `quiet`, its complaints
// are discarded.
bool run_tc(std::vector<std::string> args, bool quiet = false) {
  args.insert(args.begin(), "tc");
  std::vector<char*> argv;
  for (auto& a : args) argv.push_back(a.data());
  argv.push_back(nullptr);
  posix_spawn_file_actions_t actions;
  posix_spawn_file_actions_init(&actions);
  if (quiet) posix_spawn_file_actions_addopen(&actions, 2, "/dev/null", O_WRONLY, 0);
  pid_t pid = 0;
  const int rc = posix_spawnp(&pid, "tc", &actions, nullptr, argv.data(), environ);
  posix_spawn_file_actions_destroy(&actions);
  if (rc != 0) throw std::runtime_error(std::string("cannot run tc: ") + std::strerror(rc));
  int status = 0;
  while (waitpid(pid, &status, 0) < 0) {
    if (errno != EINTR) return false;
  }
  return WIFEXITED(status) && WEXITSTATUS(status) == 0;
}

bpf_tc_hook egress_hook(int ifindex) {
  bpf_tc_hook hook{};
  hook.sz = sizeof hook;
  hook.ifindex = ifindex;
  hook.attach_point = BPF_TC_EGRESS;
  return hook;
}

bpf_tc_opts our_filter() {
  bpf_tc_opts opts{};
  opts.sz = sizeof opts;
  opts.handle = kHandle;
  opts.priority = kPriority;
  return opts;
}

int interface_index(const std::string& dev) {
  const unsigned i = if_nametoindex(dev.c_str());
  if (i == 0) throw std::runtime_error("no interface " + dev + " here");
  return static_cast<int>(i);
}

// ---------------------------------------------------------------------- run

struct RunOptions {
  std::string dev;
  std::string trace;
  std::uint16_t port = 0;
  Nanos start = -1;
  Nanos bin = 0;
  unsigned flow_limit = 0;
};

// What run() has put on the interface, taken off again in reverse order
// however it ends.
struct Attachment {
  std::string dev;
  bpf_object* obj = nullptr;
  bpf_tc_hook hook{};
  bool root = false;    // our fq is the root qdisc
  bool clsact = false;  // we created the clsact qdisc
  bool filter = false;  // our filter is attached

  ~Attachment() {
    if (filter) {
      bpf_tc_opts opts = our_filter();
      if (bpf_tc_detach(&hook, &opts) != 0) std::fprintf(stderr, "warning: could not detach from %s\n", dev.c_str());
    }
    if (clsact) {
      hook.attach_point = static_cast<bpf_tc_attach_point>(BPF_TC_INGRESS | BPF_TC_EGRESS);
      bpf_tc_hook_destroy(&hook);
    }
    if (root && !run_tc({"qdisc", "del", "dev", dev, "root"})) {
      std::fprintf(stderr, "warning: could not remove fq from %s\n", dev.c_str());
    }
    if (obj) bpf_object__close(obj);
  }
};

struct Counts {
  std::uint64_t delayed = 0, dropped = 0, passed = 0;
};

Counts read_counts(int stats_fd) {
  const int cpus = libbpf_num_possible_cpus();
  std::vector<std::uint64_t> per_cpu(static_cast<std::size_t>(std::max(cpus, 1)));
  std::uint64_t total[NETREPLAY_STATS] = {};
  for (__u32 k = 0; k < NETREPLAY_STATS; ++k) {
    if (bpf_map_lookup_elem(stats_fd, &k, per_cpu.data()) != 0) continue;
    for (const auto v : per_cpu) total[k] += v;
  }
  return {total[NETREPLAY_DELAYED], total[NETREPLAY_DROPPED], total[NETREPLAY_PASSED]};
}

void print_counts(const char* when, const Counts& c) {
  std::fprintf(stderr, "%s: %llu UDP datagrams delayed, %llu dropped; %llu others passed\n", when,
               static_cast<unsigned long long>(c.delayed), static_cast<unsigned long long>(c.dropped),
               static_cast<unsigned long long>(c.passed));
}

int run_replay(const RunOptions& o) {
  if (o.dev.empty() || o.trace.empty()) throw std::runtime_error("run needs --dev and --trace");
  const int ifindex = interface_index(o.dev);
  const net::Trace trace = net::Trace::load_csv(o.trace);
  if (trace.entries.empty()) throw std::runtime_error(o.trace + ": no entries");
  Nanos bin = o.bin > 0 ? o.bin : trace.median_interval();
  if (bin <= 0) bin = kNanosPerMilli;
  const net::TraceGrid grid = trace.grid(bin);
  if (grid.delay.size() > 0xffffffffu) throw std::runtime_error("trace too long for its bin");
  const auto points = static_cast<__u32>(grid.delay.size());
  const Nanos max_delay = *std::max_element(grid.delay.begin(), grid.delay.end());
  const Nanos min_delay = *std::min_element(grid.delay.begin(), grid.delay.end());

  // fq holds a flow's datagrams in flight, up to flow_limit of them; the
  // default, 100, is 100 ms of a 1 kHz flow. Datagrams to leave later than
  // the horizon (10 s by default) are dropped.
  const unsigned flow_limit =
      o.flow_limit > 0 ? o.flow_limit
                       : std::max(1000u, static_cast<unsigned>(std::ceil(to_seconds(max_delay) * 20000.0)));
  const unsigned limit = std::max(10000u, 8 * flow_limit);
  const Nanos horizon = std::max<Nanos>(10 * kNanosPerSecond, 2 * max_delay);

  Attachment a;
  a.dev = o.dev;
  bpf_object_open_opts open_opts{};
  open_opts.sz = sizeof open_opts;
  open_opts.object_name = "netreplay";
  a.obj = bpf_object__open_mem(kNetreplayBpf, kNetreplayBpfSize, &open_opts);
  if (!a.obj) throw std::runtime_error(std::string("cannot open the eBPF object: ") + std::strerror(errno));
  bpf_map* points_map = bpf_object__find_map_by_name(a.obj, "points");
  if (!points_map || bpf_map__set_max_entries(points_map, points) != 0) {
    throw std::runtime_error("cannot size the points map");
  }
  if (const int err = bpf_object__load(a.obj); err != 0) {
    throw std::runtime_error(std::string("cannot load the eBPF program (root?): ") + std::strerror(-err));
  }
  const int config_fd = bpf_object__find_map_fd_by_name(a.obj, "config");
  const int points_fd = bpf_map__fd(points_map);
  const int stats_fd = bpf_object__find_map_fd_by_name(a.obj, "stats");
  bpf_program* prog = bpf_object__find_program_by_name(a.obj, "netreplay");
  if (config_fd < 0 || points_fd < 0 || stats_fd < 0 || !prog) throw std::runtime_error("eBPF object incomplete");
  for (__u32 k = 0; k < points; ++k) {
    netreplay_point p{};
    p.delay_ns = static_cast<__u64>(grid.delay[k]);
    p.lost = grid.lost[k] ? 1 : 0;
    if (bpf_map_update_elem(points_fd, &k, &p, BPF_ANY) != 0) {
      throw std::runtime_error(std::string("cannot fill the points map: ") + std::strerror(errno));
    }
  }

  if (!run_tc({"qdisc", "replace", "dev", o.dev, "root", "fq", "limit", std::to_string(limit), "flow_limit",
               std::to_string(flow_limit), "horizon", std::to_string(horizon / 1000) + "us"})) {
    throw std::runtime_error("tc could not make fq the root qdisc of " + o.dev);
  }
  a.root = true;
  a.hook = egress_hook(ifindex);
  const int created = bpf_tc_hook_create(&a.hook);
  if (created != 0 && created != -EEXIST) {
    throw std::runtime_error(std::string("cannot add clsact to ") + o.dev + ": " + std::strerror(-created));
  }
  a.clsact = created == 0;

  // The program passes everything until it has its points.
  const Nanos start = o.start >= 0 ? o.start : monotonic_now();
  netreplay_config cfg{};
  cfg.start_ns = static_cast<__u64>(start + trace.entries.front().send_offset);
  cfg.bin_ns = static_cast<__u64>(bin);
  cfg.points = points;
  cfg.port = o.port;
  const __u32 zero = 0;
  if (bpf_map_update_elem(config_fd, &zero, &cfg, BPF_ANY) != 0) throw std::runtime_error("cannot set config");

  bpf_tc_opts opts = our_filter();
  opts.prog_fd = bpf_program__fd(prog);
  opts.flags = BPF_TC_F_REPLACE;
  if (const int err = bpf_tc_attach(&a.hook, &opts); err != 0) {
    throw std::runtime_error(std::string("cannot attach to ") + o.dev + ": " + std::strerror(-err));
  }
  a.filter = true;

  const double lost = grid.loss_rate();
  std::fprintf(stderr,
               "replaying %s on %s egress%s: %u points %.3f ms apart (%.1f s, looped), delay %.3f to %.3f ms, "
               "%.2f %% lost; fq flow_limit %u, limit %u\n",
               o.trace.c_str(), o.dev.c_str(),
               o.port ? (", UDP port " + std::to_string(o.port)).c_str() : ", all UDP", points,
               static_cast<double>(bin) / 1e6, to_seconds(bin * points), static_cast<double>(min_delay) / 1e6,
               static_cast<double>(max_delay) / 1e6, 100.0 * lost, flow_limit, limit);
  if (start > monotonic_now()) {
    std::fprintf(stderr, "starts in %.3f s; datagrams pass until then\n", to_seconds(start - monotonic_now()));
  }
  Nanos next_report = monotonic_now() + 10 * kNanosPerSecond;
  while (!g_stop) {
    timespec ts{0, 200'000'000};
    nanosleep(&ts, nullptr);
    if (monotonic_now() >= next_report) {
      print_counts(o.dev.c_str(), read_counts(stats_fd));
      next_report += 10 * kNanosPerSecond;
    }
  }
  print_counts(o.dev.c_str(), read_counts(stats_fd));
  return 0;
}

int run_stop(const std::string& dev) {
  if (dev.empty()) throw std::runtime_error("stop needs --dev");
  bpf_tc_hook hook = egress_hook(interface_index(dev));
  bpf_tc_opts opts = our_filter();
  const int err = bpf_tc_detach(&hook, &opts);
  std::fprintf(stderr, "%s\n", err == 0 ? "detached the replay" : "no replay was attached");
  // The root qdisc goes back to the default whatever it was; with nothing
  // to delete, tc says so, which is not worth repeating.
  if (run_tc({"qdisc", "del", "dev", dev, "root"}, true)) std::fprintf(stderr, "removed the root qdisc\n");
  return 0;
}

// --------------------------------------------------------------- send, recv

void put_u32(std::uint8_t* p, std::uint32_t v) {
  for (int i = 0; i < 4; ++i) p[i] = static_cast<std::uint8_t>(v >> (24 - 8 * i));
}

void put_u64(std::uint8_t* p, std::uint64_t v) {
  for (int i = 0; i < 8; ++i) p[i] = static_cast<std::uint8_t>(v >> (56 - 8 * i));
}

std::uint64_t get_be(const std::uint8_t* p, int n) {
  std::uint64_t v = 0;
  for (int i = 0; i < n; ++i) v = (v << 8) | p[i];
  return v;
}

struct SendOptions {
  std::string host;
  std::uint16_t port = 0;
  double rate = 1000;
  double duration = 10;
  std::size_t size = 100;
};

int run_send(const SendOptions& o) {
  if (o.host.empty() || o.port == 0) throw std::runtime_error("send needs HOST and --port");
  if (o.rate <= 0 || o.rate > 100000) throw std::runtime_error("--rate must be in (0, 100000]");
  if (o.size < kStampSize || o.size > 1472) throw std::runtime_error("--size must be in [16, 1472]");
  const auto peer = net::Endpoint::resolve(o.host, o.port);
  if (!peer) throw std::runtime_error("cannot resolve " + o.host);
  net::UdpSocket sock(*net::Endpoint::resolve(peer->is_ipv6() ? "::" : "0.0.0.0", 0));
  const Nanos interval = static_cast<Nanos>(1e9 / o.rate);
  rt::prefer_low_latency(interval);
  const auto count = static_cast<std::uint64_t>(o.rate * o.duration);
  std::vector<std::uint8_t> d(o.size, 0);
  put_u32(d.data(), kMagic);
  std::uint64_t refused = 0;
  const Nanos t0 = monotonic_now();
  for (std::uint64_t seq = 0; seq < count && !g_stop; ++seq) {
    const Nanos at = t0 + static_cast<Nanos>(seq) * interval;
    const timespec ts{static_cast<time_t>(at / kNanosPerSecond), static_cast<long>(at % kNanosPerSecond)};
    while (clock_nanosleep(CLOCK_MONOTONIC, TIMER_ABSTIME, &ts, nullptr) == EINTR && !g_stop) {
    }
    put_u32(d.data() + 4, static_cast<std::uint32_t>(seq));
    put_u64(d.data() + 8, static_cast<std::uint64_t>(monotonic_now()));
    if (!sock.send_to(*peer, d.data(), d.size())) ++refused;
  }
  std::fprintf(stderr, "sent %llu datagrams to %s, %llu refused by the local stack\n",
               static_cast<unsigned long long>(count), peer->to_string().c_str(),
               static_cast<unsigned long long>(refused));
  return 0;
}

struct RecvOptions {
  std::uint16_t port = 0;
  std::string out;
  Nanos start = -1;
  double idle = 5;
};

int run_recv(const RecvOptions& o) {
  if (o.port == 0 || o.out.empty()) throw std::runtime_error("recv needs --port and --out");
  net::UdpSocket sock(*net::Endpoint::resolve("::", o.port));
  const bool kernel_ts = sock.enable_rx_timestamps();
  rt::prefer_low_latency();
  struct Arrival {
    Nanos sent, received;
  };
  std::map<std::uint32_t, Arrival> got;  // by sequence number; duplicates keep the first
  std::uint64_t foreign = 0;
  std::vector<std::uint8_t> in(2048);
  Nanos last = monotonic_now();
  const Nanos idle = from_seconds(o.idle);
  while (!g_stop && (got.empty() || monotonic_now() - last < idle)) {
    sock.wait_readable(100 * kNanosPerMilli);
    for (;;) {
      Nanos rx = 0;
      const auto n = sock.recv_from(in.data(), in.size(), nullptr, &rx);
      if (!n) break;
      if (*n < kStampSize || get_be(in.data(), 4) != kMagic) {
        ++foreign;
        continue;
      }
      const auto seq = static_cast<std::uint32_t>(get_be(in.data() + 4, 4));
      got.emplace(seq, Arrival{static_cast<Nanos>(get_be(in.data() + 8, 8)), rx});
      last = monotonic_now();
    }
  }
  if (got.empty()) throw std::runtime_error("nothing received");

  // Every number from the first received to the last: a missing one was
  // lost, sent at the time interpolated between its neighbours.
  const Nanos start = o.start >= 0 ? o.start : got.begin()->second.sent;
  net::Trace t;
  t.comments.push_back("tuushin-netreplay recv on port " + std::to_string(o.port) + ", " +
                       (kernel_ts ? "kernel" : "user-space") + " receive stamps, send_ns from " +
                       std::to_string(start) + " (CLOCK_MONOTONIC)");
  auto it = got.begin();
  for (auto next = std::next(it); next != got.end(); it = next++) {
    t.entries.push_back({it->second.sent - start, it->second.received - it->second.sent});
    const std::uint32_t gap = next->first - it->first;
    for (std::uint32_t k = 1; k < gap; ++k) {
      const Nanos s = it->second.sent + (next->second.sent - it->second.sent) * k / gap;
      t.entries.push_back({s - start, -1});
    }
  }
  t.entries.push_back({it->second.sent - start, it->second.received - it->second.sent});
  t.save_csv(o.out);
  std::fprintf(stderr, "received %zu of %zu datagrams (%.2f %% lost)%s; wrote %s\n", got.size(), t.entries.size(),
               100.0 * t.loss_rate(), foreign ? ", and others" : "", o.out.c_str());
  return 0;
}

// ------------------------------------------------------------------ compare

double percentile(std::vector<Nanos> v, double p) {
  if (v.empty()) return 0;
  const auto k = static_cast<std::size_t>(std::llround(p * static_cast<double>(v.size() - 1)));
  std::nth_element(v.begin(), v.begin() + static_cast<std::ptrdiff_t>(k), v.end());
  return static_cast<double>(v[k]);
}

int run_compare(const std::string& trace_path, const std::string& recorded_path, Nanos bin_opt) {
  if (trace_path.empty() || recorded_path.empty()) throw std::runtime_error("compare needs --trace and --recorded");
  const net::Trace trace = net::Trace::load_csv(trace_path);
  const net::Trace rec = net::Trace::load_csv(recorded_path);
  Nanos bin = bin_opt > 0 ? bin_opt : trace.median_interval();
  if (bin <= 0) bin = kNanosPerMilli;
  const net::TraceGrid grid = trace.grid(bin);
  const Nanos first = trace.entries.front().send_offset;
  std::uint64_t n = 0, both_lost = 0, leaked = 0, extra_lost = 0;
  std::uint64_t reordered = 0, reordered_expected = 0;
  std::vector<Nanos> error;
  Nanos last = INT64_MIN, last_expected = INT64_MIN;
  for (const auto& e : rec.entries) {
    if (e.send_offset < first) continue;  // sent before the replay began
    ++n;
    const Nanos expected = grid.delay_at(e.send_offset - first);
    if (expected >= 0) {
      if (e.send_offset + expected < last_expected) ++reordered_expected;
      last_expected = std::max(last_expected, e.send_offset + expected);
    }
    if (e.lost()) {
      if (expected < 0) ++both_lost;
      else ++extra_lost;
      continue;
    }
    if (e.send_offset + e.delay < last) ++reordered;
    last = std::max(last, e.send_offset + e.delay);
    if (expected < 0) {
      ++leaked;
      continue;
    }
    error.push_back(e.delay - expected);
  }
  if (n == 0) throw std::runtime_error("no recorded datagram was sent after the replay began");
  const double us = 1e3;
  std::printf("%llu datagrams: %llu lost where the trace lost (%.2f %%), %llu lost elsewhere, "
              "%llu delivered where the trace lost\n",
              static_cast<unsigned long long>(n), static_cast<unsigned long long>(both_lost),
              100.0 * static_cast<double>(both_lost) / static_cast<double>(n),
              static_cast<unsigned long long>(extra_lost), static_cast<unsigned long long>(leaked));
  std::printf("delay minus the trace's, us: min %.1f, median %.1f, p99 %.1f, p99.9 %.1f, max %.1f\n",
              percentile(error, 0) / us, percentile(error, 0.5) / us, percentile(error, 0.99) / us,
              percentile(error, 0.999) / us, percentile(error, 1) / us);
  std::printf("reordered: %llu (the trace: %llu)\n", static_cast<unsigned long long>(reordered),
              static_cast<unsigned long long>(reordered_expected));
  return 0;
}

